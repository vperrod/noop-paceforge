#!/usr/bin/env python3
"""Writes NOOPiOSUITests/PerfRealCounts.swift: how many items each list in the live PaceForge documents holds.

The perf UI test grows the synthetic StrandTests/LiveShapes/PaceForgeRealShapes.json (the live shapes with every value
replaced, a few items per list) to these lengths, so the PaceForge tab is measured on documents of real size without
any real value in the repository. Only list lengths leave the private directory: no value, no text, no date.

Usage: scripts/pf-perf-counts.py <private dir of the served documents> > NOOPiOSUITests/PerfRealCounts.swift
"""
import json
import os
import sys

SHAPES = "StrandTests/LiveShapes/PaceForgeRealShapes.json"


def walk(node, path, out):
    """out[path] = the longest list seen at path; "[]" stands for every item of a list."""
    if isinstance(node, list):
        out[path] = max(out.get(path, 0), len(node))
        for item in node:
            walk(item, path + "[]", out)
    elif isinstance(node, dict):
        for key, value in node.items():
            walk(value, f"{path}.{key}", out)


def main():
    src = sys.argv[1]
    shapes = json.load(open(SHAPES))["docs"]
    rows = {}
    for doc, shape in shapes.items():
        try:
            real = json.load(open(os.path.join(src, doc.replace("/", "__"))))
        except (OSError, ValueError):
            continue
        real_counts, shape_counts = {}, {}
        walk(real, doc, real_counts)
        walk(shape, doc, shape_counts)
        for path, n in real_counts.items():
            if n > shape_counts.get(path, 0) and shape_counts.get(path, 0) > 0 and n >= 4:
                rows[path] = n
    print("// Generated by scripts/pf-perf-counts.py: the longest list at each path of the live PaceForge documents.")
    print("// List lengths only (no value, text or date). PerfHarnessUITests grows PaceForgeRealShapes.json to them.")
    print("enum PerfRealCounts {")
    print("    static let lengths: [String: Int] = [")
    for path in sorted(rows):
        print(f'        "{path}": {rows[path]},')
    print("    ]")
    print("}")


if __name__ == "__main__":
    main()
